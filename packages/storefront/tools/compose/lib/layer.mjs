// Brand layer directory: brand.json, overlay/, overlay.manifest.json,
// overlay.base/ (snapshots of ejected base files), pnpm-lock.yaml, e2e/.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import {
	ComposeError,
	PIN_RE,
	Problems,
	SHA_RE,
	fileSha,
	readJson,
	realDir,
	treeHash,
	unsafeRelReason,
	walkFiles,
} from './util.mjs';
import { layerOf } from './layers.mjs';

export const SCRIPT_KEY_ALLOWLIST = ['build', 'prebuild', 'build.client', 'build.server'];
export const scriptEntryId = (key) => `package.json#scripts.${key}`;
export const snapshotKey = (entry) => (entry.kind === 'package-script' ? `@scripts/${entry.key}.txt` : entry.path);

/** Paths no overlay file may occupy: compose generates or owns them. */
const RESERVED_OVERLAY = new Set(['package.json', 'pnpm-workspace.yaml', 'pnpm-lock.yaml', 'tsconfig.base.json', 'compose-report.json']);
export function reservedOverlayReason(rel) {
	const top = rel.split('/')[0];
	if (RESERVED_OVERLAY.has(rel)) return `${rel} is generated by compose`;
	if (top === 'vendor') return 'vendor/ is copied from the pin and is not overlayable';
	if (top === 'node_modules' || top.startsWith('dist') || top.startsWith('server') || top === '.cache' || top === 'tmp') {
		return `${top} is runtime state and never composed`;
	}
	if (top.startsWith('.env')) return 'env files are never composed from an overlay (public config comes from brand.json)';
	if (top.startsWith('.compose-')) return '.compose-* files are compose bookkeeping';
	return null;
}

export function loadLayer(dir) {
	const root = realDir(dir, 'brand layer');
	const all = walkFiles(root);
	const files = all.map((f) => ({ ...f, sha: fileSha(f.abs) }));
	const byRel = new Map(files.map((f) => [f.rel, f]));
	for (const need of ['brand.json', 'overlay.manifest.json', 'pnpm-lock.yaml']) {
		if (!byRel.has(need)) throw new ComposeError('missing-file', `brand layer lacks ${need}`);
	}
	const overlay = new Map();
	const snapshots = new Map();
	for (const f of files) {
		if (f.rel.startsWith('overlay/')) overlay.set(f.rel.slice('overlay/'.length), f);
		else if (f.rel.startsWith('overlay.base/')) snapshots.set(f.rel.slice('overlay.base/'.length), f);
	}
	return {
		dir: root,
		files,
		brand: readJson(path.join(root, 'brand.json'), 'brand.json'),
		manifest: readJson(path.join(root, 'overlay.manifest.json'), 'overlay.manifest.json'),
		manifestSha: byRel.get('overlay.manifest.json').sha,
		lockSha: byRel.get('pnpm-lock.yaml').sha,
		lockBuf: readFileSync(byRel.get('pnpm-lock.yaml').abs),
		overlay,
		snapshots,
		overlayTreeHash: treeHash([...overlay].map(([k, f]) => [k, f.sha])),
	};
}

export function validateBrand(brand, problems = new Problems()) {
	const b = brand;
	if (!b || typeof b !== 'object' || Array.isArray(b)) {
		problems.add('bad-brand', 'brand.json must be an object', 'brand.json');
		return problems;
	}
	if (typeof b.brand !== 'string' || !b.brand) problems.add('bad-brand', 'brand must be a non-empty string', 'brand.json');
	if (typeof b.buildDir !== 'string' || unsafeRelReason(b.buildDir) || b.buildDir.includes('/')) {
		problems.add('bad-brand', 'buildDir must be a single safe path segment', 'brand.json');
	}
	if (!PIN_RE.test(b.pin ?? '')) problems.add('bad-pin', 'pin must be a full 40-character lowercase SHA', 'brand.json');
	for (const k of ['settings', 'publicConfig', 'packageScripts']) {
		if (b[k] !== undefined && (typeof b[k] !== 'object' || b[k] === null || Array.isArray(b[k]))) {
			problems.add('bad-brand', `${k} must be an object`, 'brand.json');
		}
	}
	for (const k of ['requiredEnv', 'externals', 'deployFiles', 'baseExclude']) {
		if (b[k] !== undefined && (!Array.isArray(b[k]) || b[k].some((s) => typeof s !== 'string'))) {
			problems.add('bad-brand', `${k} must be a list of strings`, 'brand.json');
		}
	}
	for (const p of b.deployFiles ?? []) {
		const r = unsafeRelReason(p);
		if (r) problems.add('unsafe-path', `deployFiles ${JSON.stringify(p)}: ${r}`, 'brand.json');
	}
	for (const [k, v] of Object.entries(b.packageScripts ?? {})) {
		if (!SCRIPT_KEY_ALLOWLIST.includes(k)) problems.add('script-not-allowed', `packageScripts key ${k} is not in the allowlist (${SCRIPT_KEY_ALLOWLIST.join(', ')})`, 'brand.json');
		if (v !== null && typeof v !== 'string') problems.add('bad-brand', `packageScripts.${k} must be a string or null`, 'brand.json');
	}
	if (b.buildScript !== undefined && (typeof b.buildScript !== 'string' || unsafeRelReason(b.buildScript))) {
		problems.add('bad-brand', 'buildScript must be a safe relative path', 'brand.json');
	}
	return problems;
}

/**
 * Validates overlay.manifest.json against the overlay directory, layers and base.
 * Entry shape:
 *   file:           { path, layer: 'L2'|'L3', baseHash, baseSnapshotHash, fromPin, resolution? }  (L3 needs none of the hashes)
 *   package-script: { kind: 'package-script', key, layer: 'L2', baseHash, baseSnapshotHash, fromPin, resolution? }
 */
export function validateManifest({ layer, layers, base, problems = new Problems() }) {
	const m = layer.manifest;
	if (!m || m.version !== 1 || !Array.isArray(m.entries)) {
		problems.add('bad-manifest', 'overlay.manifest.json must be { "version": 1, "entries": [...] }', 'overlay.manifest.json');
		return problems;
	}
	const seen = new Set();
	const entryByPath = new Map();
	for (const e of m.entries) {
		const kind = e?.kind ?? 'file';
		if (kind === 'package-script') {
			if (!SCRIPT_KEY_ALLOWLIST.includes(e.key)) {
				problems.add('script-not-allowed', `manifest package-script key ${JSON.stringify(e.key)} is not allowed`, 'overlay.manifest.json');
				continue;
			}
			const id = scriptEntryId(e.key);
			if (seen.has(id)) problems.add('duplicate-entry', `duplicate manifest entry ${id}`, 'overlay.manifest.json');
			seen.add(id);
			if (e.layer !== 'L2') problems.add('spoofed-layer', `${id} must declare layer L2`, 'overlay.manifest.json');
			checkEjectHashes(e, id, problems);
			continue;
		}
		if (kind !== 'file') {
			problems.add('bad-manifest', `unknown entry kind ${JSON.stringify(kind)}`, 'overlay.manifest.json');
			continue;
		}
		const reason = unsafeRelReason(e.path);
		if (reason) {
			problems.add('unsafe-path', `manifest path ${JSON.stringify(e.path)}: ${reason}`, 'overlay.manifest.json');
			continue;
		}
		if (seen.has(e.path)) problems.add('duplicate-entry', `duplicate manifest entry ${e.path}`, 'overlay.manifest.json');
		seen.add(e.path);
		entryByPath.set(e.path, e);
		let actual;
		try {
			actual = layerOf(layers, e.path);
		} catch (err) {
			problems.add(err.code ?? 'ambiguous-layer', err.message, e.path);
			continue;
		}
		if (e.layer !== actual) {
			problems.add('spoofed-layer', `manifest declares ${e.path} as ${e.layer} but layers.json classifies it as ${actual ?? 'unlayered'}`, e.path);
			continue;
		}
		if (e.layer === 'L2') checkEjectHashes(e, e.path, problems);
		if (!layer.overlay.has(e.path)) problems.add('eject-missing-file', `manifest lists ${e.path} but overlay/ has no such file`, e.path);
	}

	const deploy = new Set(layer.brand?.deployFiles ?? []);
	for (const rel of [...layer.overlay.keys()].sort()) {
		const reason = unsafeRelReason(rel);
		if (reason) {
			problems.add('unsafe-path', `overlay path ${JSON.stringify(rel)}: ${reason}`, `overlay/${rel}`);
			continue;
		}
		const res = reservedOverlayReason(rel);
		if (res) {
			problems.add('reserved-path', res, `overlay/${rel}`);
			continue;
		}
		let l;
		try {
			l = layerOf(layers, rel);
		} catch (err) {
			problems.add(err.code ?? 'ambiguous-layer', err.message, `overlay/${rel}`);
			continue;
		}
		const entry = entryByPath.get(rel);
		if (l === 'L1') problems.add('overlay-in-l1', `${rel} is an L1 platform path; L1 is not ejectable or overlayable`, `overlay/${rel}`);
		else if (l === 'L2') {
			if (!entry || entry.layer !== 'L2') problems.add('undeclared-eject', `${rel} is an L2 path and needs an L2 eject entry in overlay.manifest.json`, `overlay/${rel}`);
			else if (!base.has(rel)) problems.add('orphaned-eject', `${rel} is declared as an eject but the base has no such file at the pin`, `overlay/${rel}`);
		} else if (l === 'L3') {
			/* brand-owned; an entry is optional */
		} else if (!deploy.has(rel)) {
			problems.add('unlayered-overlay', `${rel} matches no layer and is not listed in brand.json deployFiles`, `overlay/${rel}`);
		}
	}
	return problems;
}

function checkEjectHashes(e, id, problems) {
	if (!SHA_RE.test(e.baseHash ?? '')) problems.add('bad-eject', `${id}: baseHash must be a sha256 hex`, id);
	if (!SHA_RE.test(e.baseSnapshotHash ?? '')) problems.add('bad-eject', `${id}: baseSnapshotHash must be a sha256 hex`, id);
	if (!PIN_RE.test(e.fromPin ?? '')) problems.add('bad-eject', `${id}: fromPin must be a full 40-character SHA`, id);
	if (e.resolution !== undefined) {
		const r = e.resolution;
		if (!r || typeof r !== 'object' || !PIN_RE.test(r.pin ?? '') || !SHA_RE.test(r.baseHash ?? '') || typeof r.text !== 'string' || !r.text) {
			problems.add('bad-eject', `${id}: resolution needs { pin, baseHash, text }`, id);
		}
	}
}
