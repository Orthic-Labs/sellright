let cachedDerBuffers: Buffer[] | null = null;

/** DER-encoded Apple root certificates, verified against their pinned
 *  fingerprints. Pass the result straight to `SignedDataVerifier`'s first
 *  constructor argument. Throws (fail loud, not silent) if a pin does not
 *  match — this must never happen outside of the constant being edited by
 *  mistake, since the PEMs are literal, not fetched at runtime. */
export function appleRootCertificateDerBuffers(): Buffer[] {
  if (cachedDerBuffers) return cachedDerBuffers;
  cachedDerBuffers = PINNED_ROOTS.map((root) => {
    const cert = new X509Certificate(root.pem);
    if (cert.fingerprint256 !== root.sha256Fingerprint) {
      throw new Error(`apple-root-certificates: "${root.name}" fingerprint does not match its pin — refusing to trust it`);
    }
    return cert.raw;
  });
  return cachedDerBuffers;
}
