// Apple's published root certificates, for use as the trust anchors passed
// to `@apple/app-store-server-library`'s `SignedDataVerifier` in
// storekit-verify.ts.
//
// storekit-official-verifier (2026-09-01): the verifier this module used to
// back (the hand-rolled one, now deleted) pinned only ONE root — Apple Root
// CA G3. Apple's real trust set is not a single hardcoded root: as of this
// writing, https://www.apple.com/certificateauthority/ ("Apple Root
// Certificates" section) publishes THREE:
//   - Apple Inc. Root                 (https://www.apple.com/appleca/AppleIncRootCertificate.cer)
//   - Apple Root CA - G2               (https://www.apple.com/certificateauthority/AppleRootCA-G2.cer)
//   - Apple Root CA - G3               (https://www.apple.com/certificateauthority/AppleRootCA-G3.cer)
// StoreKit 2 / App Store Server JWS transactions are signed through a chain
// that terminates at G3 in practice today, but the vendor library's own
// documented usage (https://apple.github.io/app-store-server-library-node/,
// "Obtaining Apple Root Certificates") is to hand SignedDataVerifier the
// FULL published root set, not just the one currently in use — this is what
// lets verification keep working across an Apple-side root rotation without
// a code change here. All three are embedded below (fetched 2026-09-01
// directly from the URLs above) and fingerprint-pinned so the constants
// cannot silently drift from what was actually fetched.
